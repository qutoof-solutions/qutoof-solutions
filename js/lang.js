function getByPath(source, path) {
  return path.split(".").reduce((value, key) => value?.[key], source);
}

export function getCurrentLanguage() {
  try {
    const saved = window.localStorage.getItem("qutoof-language");
    return saved === "ar" || saved === "en" ? saved : "en";
  } catch {
    return "en";
  }
}

export function applyLanguage(language = getCurrentLanguage()) {
  const lang = language === "ar" ? "ar" : "en";
  const dictionary = copy[lang];
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  html.classList.toggle("is-rtl", lang === "ar");
  document.body.dataset.language = lang;
  document.title = dictionary.meta.title;
  document.querySelector('meta[name="description"]')?.setAttribute("content", dictionary.meta.description);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18n);
    if (typeof value === "string") element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18nHtml);
    if (typeof value === "string") element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18nPlaceholder);
    if (typeof value === "string") element.setAttribute("placeholder", value);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = getByPath(dictionary, element.dataset.i18nAria);
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });

  document.querySelectorAll(".language-option").forEach((button) => {
    const active = button.dataset.language === lang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  try {
    window.localStorage.setItem("qutoof-language", lang);
  } catch {
    // The language still changes for this visit when storage is unavailable.
  }
  window.dispatchEvent(new CustomEvent("qutoof:language-change", { detail: { language: lang } }));
  return lang;
}

export function installLanguageSwitch() {
  document.querySelectorAll(".language-option").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.language));
  });
}
